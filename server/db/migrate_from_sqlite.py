"""One-off migration: copies every local store (~/.mads/chats.db,
~/.mads/memory.sqlite3, ~/.mads/projects/*/{project,tasks}.json,
~/.mads/adaptive/{profile,pending,ledger}.json) into the Postgres schema
in server/db/schema.sql.

Idempotency and transaction behavior (audit finding F-07 — this section
previously overstated what's actually implemented): every insert is
ON CONFLICT DO NOTHING, so re-running this script from the start after an
earlier full run (or a run that failed and rolled back) is always safe and
just fills in whatever's still missing. That is NOT the same as resuming
mid-run: main() runs every migrate_* call inside the one transaction
opened by `with psycopg.connect(...) as pg:`, so a failure partway through
rolls back everything from that run, including tables that had already
migrated successfully earlier in the same run. There is no partial-commit
checkpointing within a single execution — "idempotent" here means
"safe to re-run from zero," not "resumable from where it stopped."

Run with: uv run python3 -m server.db.migrate_from_sqlite
"""

from __future__ import annotations

import json
import os
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

import psycopg
import psycopg.sql
from dotenv import load_dotenv

MADS_HOME = Path.home() / ".mads"


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def _sqlite(path: Path) -> sqlite3.Connection:
    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row
    return conn


def _sync_identity_sequence(pg: psycopg.Connection, table: str, column: str = "id") -> None:
    """Advance `table`'s IDENTITY sequence past the highest id actually
    present, after a batch of explicit-id inserts into it (audit finding
    F-03).

    Why this is needed at all: Postgres's GENERATED BY DEFAULT AS IDENTITY
    only auto-assigns a value when an insert omits the column — an insert
    that supplies an explicit id (every migrate_* call below, copying ids
    straight from the old SQLite tables) bypasses the sequence entirely,
    so it never advances on its own. Left alone, the sequence stays at its
    initial state (effectively "1"), and the very next *normal* insert
    from the running app — which never specifies an id, by design — can
    generate a value that collides with an already-migrated row and raise
    a primary-key/unique-constraint violation.

    Safety properties, each load-bearing for a specific audit requirement:
      - GREATEST(...) against the sequence's own current last_value means
        this can only move the sequence forward, never backward — calling
        it on an empty table, an already-synced table, or a table whose
        sequence is already ahead (e.g. rows were since deleted) is a
        correctly-handled no-op, not a regression.
      - pg_get_serial_sequence resolves the real underlying sequence from
        Postgres's own catalog rather than assuming a naming convention,
        so this is correct for any IDENTITY/serial column regardless of
        how its sequence happens to be named.
      - Table/column names are passed through psycopg.sql.Identifier
        (never f-string/% interpolation) even though every call site here
        uses a fixed, hardcoded string — defense in depth, not because
        these particular values are attacker-reachable.
      - setval's is_called=true means the NEXT nextval() returns
        value + 1, i.e. strictly after the highest id this run has seen,
        not equal to it.
    """
    with pg.cursor() as cur:
        cur.execute("SELECT pg_get_serial_sequence(%s, %s)", (table, column))
        row = cur.fetchone()
        seq_name = row[0] if row else None
        if seq_name is None:
            # Not an identity/serial column (e.g. sessions.id is a plain
            # TEXT primary key) — nothing to synchronize.
            return

        # Reading the sequence's own current last_value requires it to
        # appear as a genuine table reference, which a cast expression
        # ('text'::regclass) cannot be used as directly in a FROM clause —
        # confirmed by testing (Postgres raises a syntax error on
        # `FROM 'name'::regclass`). Resolving the OID once and joining
        # pg_class/pg_namespace/pg_sequences by it instead keeps every
        # value here fully parameterized, with no dynamic SQL text built
        # from seq_name at all.
        #
        # pg_sequences.last_value is documented as NULL specifically when
        # nextval() has never been called on the sequence (confirmed by
        # testing against a freshly created table/sequence, which raised
        # "value 0 is out of bounds" without this COALESCE — GREATEST
        # ignores NULL arguments entirely rather than propagating them, so
        # an un-COALESCEd NULL here silently collapsed to just the
        # MAX(id) side). A sequence that's never been read from is
        # equivalent to "currently at its start value" (1) for comparison
        # purposes.
        cur.execute(
            psycopg.sql.SQL(
                """
                SELECT setval(
                    %(seq)s::regclass,
                    GREATEST(
                        (SELECT COALESCE(MAX({col}), 0) FROM {table}),
                        (
                            SELECT COALESCE(ps.last_value, 1)
                            FROM pg_class c
                            JOIN pg_namespace n ON n.oid = c.relnamespace
                            JOIN pg_sequences ps ON ps.schemaname = n.nspname AND ps.sequencename = c.relname
                            WHERE c.oid = %(seq)s::regclass
                        )
                    ),
                    true
                )
                """
            ).format(
                col=psycopg.sql.Identifier(column),
                table=psycopg.sql.Identifier(table),
            ),
            {"seq": seq_name},
        )


def migrate_chats(pg: psycopg.Connection) -> None:
    db_path = MADS_HOME / "chats.db"
    if not db_path.exists():
        print("chats.db not found — skipping")
        return
    with _sqlite(db_path) as conn:
        sessions = conn.execute("SELECT * FROM sessions").fetchall()
        messages = conn.execute("SELECT * FROM messages").fetchall()

    with pg.cursor() as cur:
        for s in sessions:
            cur.execute(
                """
                INSERT INTO sessions (id, title, created_at, updated_at)
                VALUES (%s, %s, %s, %s)
                ON CONFLICT (id) DO NOTHING
                """,
                (s["id"], s["title"], s["created_at"], s["updated_at"]),
            )
        for m in messages:
            cur.execute(
                """
                INSERT INTO messages (id, session_id, role, text, tool_calls, files, created_at)
                VALUES (%s, %s, %s, %s, %s, %s, %s)
                ON CONFLICT (id) DO NOTHING
                """,
                (m["id"], m["session_id"], m["role"], m["text"], m["tool_calls"], m["files"], m["created_at"]),
            )
    # sessions.id is a plain TEXT primary key (gen_random_uuid()), not an
    # identity column — only messages.id needs syncing here.
    _sync_identity_sequence(pg, "messages")
    print(f"chats: {len(sessions)} sessions, {len(messages)} messages")


def migrate_memory(pg: psycopg.Connection) -> None:
    db_path = MADS_HOME / "memory.sqlite3"
    if not db_path.exists():
        print("memory.sqlite3 not found — skipping")
        return
    with _sqlite(db_path) as conn:
        rows = conn.execute("SELECT * FROM memories").fetchall()

    with pg.cursor() as cur:
        for r in rows:
            cur.execute(
                """
                INSERT INTO memories (id, category, content, tags, created_at, updated_at)
                VALUES (%s, %s, %s, %s, %s, %s)
                ON CONFLICT (id) DO NOTHING
                """,
                (r["id"], r["category"], r["content"], r["tags"], r["created_at"], r["updated_at"]),
            )
    _sync_identity_sequence(pg, "memories")
    print(f"memory: {len(rows)} memories")


def migrate_planner(pg: psycopg.Connection) -> None:
    projects_root = MADS_HOME / "projects"
    if not projects_root.exists():
        print("projects/ not found — skipping")
        return

    project_count = 0
    task_count = 0
    prompt_count = 0

    with pg.cursor() as cur:
        for project_dir in sorted(projects_root.iterdir()):
            project_json = project_dir / "project.json"
            if not project_json.exists():
                continue
            p = json.loads(project_json.read_text())
            cur.execute(
                """
                INSERT INTO projects (slug, name, github_repo, folder, drive_folder, tags, created_at, last_active_at)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                ON CONFLICT (slug) DO NOTHING
                """,
                (
                    p["slug"], p["name"], p.get("github_repo"), p.get("folder"), p.get("drive_folder"),
                    p.get("tags", []), p["created_at"], p.get("last_active_at"),
                ),
            )
            project_count += 1

            tasks_json = project_dir / "tasks.json"
            if tasks_json.exists():
                for t in json.loads(tasks_json.read_text()):
                    cur.execute(
                        """
                        INSERT INTO tasks (id, project_slug, title, description, priority, status,
                                           due_date, tags, created_at, updated_at, completed_at)
                        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                        ON CONFLICT (id) DO NOTHING
                        """,
                        (
                            t["id"], t["project_slug"], t["title"], t.get("description", ""),
                            t.get("priority", "medium"), t.get("status", "open"), t.get("due_date"),
                            t.get("tags", []), t["created_at"], t["updated_at"], t.get("completed_at"),
                        ),
                    )
                    task_count += 1

            prompts_dir = project_dir / "prompts"
            if prompts_dir.exists():
                prompt_count += _migrate_prompt_dir(cur, prompts_dir, project_slug=p["slug"])

        global_prompts_dir = MADS_HOME / "prompts" / "global"
        if global_prompts_dir.exists():
            prompt_count += _migrate_prompt_dir(cur, global_prompts_dir, project_slug=None)

    # projects.slug is a TEXT primary key and prompts.id is always
    # DEFAULT-generated here (never passed explicitly — see
    # _migrate_prompt_dir's INSERT column list), so only tasks.id needs
    # syncing.
    _sync_identity_sequence(pg, "tasks")
    print(f"planner: {project_count} projects, {task_count} tasks, {prompt_count} prompts")


def _migrate_prompt_dir(cur: psycopg.Cursor, prompts_dir: Path, project_slug: str | None) -> int:
    """Prompts are markdown files with a frontmatter block written by
    planner/prompt_library.py's _format_frontmatter — slug is the filename
    stem (never stored in the frontmatter itself), and dates use the keys
    `created`/`updated`, not `created_at`/`updated_at`. Mirrors
    _parse_prompt_file's parsing exactly rather than re-deriving it.
    """
    count = 0
    for md_file in prompts_dir.glob("*.md"):
        text = md_file.read_text()
        if not text.startswith("---"):
            continue
        _, frontmatter, body = text.split("---", 2)
        meta: dict[str, str] = {}
        for line in frontmatter.strip().splitlines():
            if ":" in line:
                key, _, value = line.partition(":")
                meta[key.strip()] = value.strip()

        cur.execute(
            """
            INSERT INTO prompts (slug, title, description, category, body, tags, scope,
                                  project_slug, favorite, created_at, updated_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            ON CONFLICT (slug) DO NOTHING
            """,
            (
                md_file.stem, meta.get("title", md_file.stem), meta.get("description", ""),
                meta.get("category", "general"), body.strip("\n"),
                [t.strip() for t in meta.get("tags", "").split(",") if t.strip()],
                "project" if project_slug else "global", project_slug,
                meta.get("favorite", "false").lower() == "true",
                meta.get("created") or _now_iso(), meta.get("updated") or _now_iso(),
            ),
        )
        count += 1
    return count


def migrate_adaptive(pg: psycopg.Connection) -> None:
    adaptive_home = MADS_HOME / "adaptive"

    pending_path = adaptive_home / "pending.json"
    approved_count = 0
    pending_count = 0
    with pg.cursor() as cur:
        if pending_path.exists():
            for c in json.loads(pending_path.read_text()):
                cur.execute(
                    """
                    INSERT INTO adaptive_pending_candidates
                        (id, category, statement, confidence, recurrence,
                         source_conversation_ids, contradicts, status, created_at)
                    VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
                    ON CONFLICT (id) DO NOTHING
                    """,
                    (
                        c["id"], c["category"], c["statement"], c["confidence"], c["recurrence"],
                        c.get("source_conversation_ids", []), c.get("contradicts", []),
                        c.get("status", "pending"), c["created_at"],
                    ),
                )
                pending_count += 1

        profile_path = adaptive_home / "profile.json"
        if profile_path.exists():
            for f in json.loads(profile_path.read_text()):
                cur.execute(
                    """
                    INSERT INTO adaptive_approved_facts
                        (id, category, statement, confidence, approved_at, source_conversation_ids)
                    VALUES (%s, %s, %s, %s, %s, %s)
                    ON CONFLICT (id) DO NOTHING
                    """,
                    (
                        f["id"], f["category"], f["statement"], f["confidence"],
                        f["approved_at"], f.get("source_conversation_ids", []),
                    ),
                )
                approved_count += 1

        ledger_path = adaptive_home / "ledger.json"
        ledger_count = 0
        if ledger_path.exists():
            for entry in json.loads(ledger_path.read_text()):
                cur.execute(
                    """
                    INSERT INTO adaptive_ledger (conversation_id, content_hash, processed_at, outcome)
                    VALUES (%s, %s, %s, %s)
                    ON CONFLICT (conversation_id) DO NOTHING
                    """,
                    (entry["conversation_id"], entry["content_hash"], entry["processed_at"], entry["outcome"]),
                )
                ledger_count += 1

    # adaptive_ledger.conversation_id is a TEXT primary key — only the two
    # identity-backed tables need syncing.
    _sync_identity_sequence(pg, "adaptive_pending_candidates")
    _sync_identity_sequence(pg, "adaptive_approved_facts")
    print(f"adaptive: {pending_count} pending, {approved_count} approved, {ledger_count} ledger entries")


def main() -> None:
    load_dotenv()
    with psycopg.connect(os.environ["DATABASE_URL"]) as pg:
        migrate_chats(pg)
        migrate_memory(pg)
        migrate_planner(pg)
        migrate_adaptive(pg)
        pg.commit()
    print("Migration complete.")


if __name__ == "__main__":
    main()
